// GLM OS interrupt stubs (GNU as, Intel syntax).
// Push a dummy error code (where the CPU doesn't), all GP registers,
// pass (vector, regs_ptr) to the Rust dispatcher and iretq back.

.macro PUSH_GPRS
  push rax
  push rbx
  push rcx
  push rdx
  push rsi
  push rdi
  push rbp
  push r8
  push r9
  push r10
  push r11
  push r12
  push r13
  push r14
  push r15
.endmacro

.macro POP_GPRS
  pop r15
  pop r14
  pop r13
  pop r12
  pop r11
  pop r10
  pop r9
  pop r8
  pop rbp
  pop rdi
  pop rsi
  pop rdx
  pop rcx
  pop rbx
  pop rax
.endmacro

.macro ISR vec, has_err
.global isr_\vec
isr_\vec:
  .if \has_err == 0
    push 0
  .endif
  PUSH_GPRS
  mov edi, \vec
  mov rsi, rsp
  cld
  call common_handler
  POP_GPRS
  add rsp, 8
  iretq
.endmacro

